// Шаблоны — массивом: добавление нового формата секрета (например, ключа нового брокера) —
// это одна строка, а не правка регэкспа целиком. Ведущий \b есть у всех (не матчить токен
// внутри случайного слова), а вот завершающего \b у T-Invest и Telegram намеренно нет — токен
// может кончаться на `-`/другой не-\w символ, и \b на границе «не-\w → конец строки» не
// сработает, обрезая совпадение раньше времени.
//
// replaceAll с regex, у которого флаг g, сбрасывает lastIndex перед каждым вызовом — в
// отличие от .test()/.exec() на том же глобальном regex-объекте, которые lastIndex не
// сбрасывают и делят его между вызовами. Эти regex-объекты — общие, на уровне модуля: если
// когда-нибудь вместо replaceAll здесь появится .test()/.exec(), результат начнёт зависеть
// от порядка предыдущих вызовов. Тест ниже — регресс на этот случай.
const SECRET_PATTERNS: readonly { pattern: RegExp; mask: string }[] = [
  { pattern: /\bt\.[\w-]{20,}/g, mask: 't.***' }, // токен T-Invest API
  { pattern: /\b\d{6,}:[\w-]{30,}/g, mask: '[telegram-bot-token]' }, // токен Telegram-бота
  { pattern: /\bBearer\s+[\w.-]{10,}/gi, mask: 'Bearer [masked]' }, // Authorization: Bearer …
];

export function maskSecrets(text: string): string {
  return SECRET_PATTERNS.reduce((acc, { pattern, mask }) => acc.replaceAll(pattern, mask), text);
}
